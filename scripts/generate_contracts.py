"""Generate frontend scope and metric contracts from their Python definitions."""

from __future__ import annotations

import argparse
import json
import sys
from dataclasses import fields
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))


def typescript_type(schema: dict[str, Any]) -> str:
    if "enum" in schema:
        return " | ".join(repr(value) for value in schema["enum"])
    if "anyOf" in schema:
        return " | ".join(typescript_type(item) for item in schema["anyOf"])
    kind = schema.get("type")
    mapping = {
        "integer": "number",
        "number": "number",
        "string": "string",
        "boolean": "boolean",
        "null": "null",
    }
    if kind not in mapping:
        raise ValueError("Unsupported generated contract field: " + json.dumps(schema))
    return mapping[kind]


def metric_typescript(name: str, schema: dict[str, Any]) -> list[str]:
    if set(schema["required"]) != set(schema["properties"]):
        raise ValueError("Metric contract fields must all be required")
    declarations = []
    for key, value in schema["properties"].items():
        value_type = typescript_type(value)
        declaration = f"  {key}: {value_type};"
        if len(declaration) > 100:
            declaration = f"  {key}:\n    {value_type};"
        declarations.append(declaration)
    return [
        f"export type {name} = {{",
        *declarations,
        "};",
        "",
    ]


def scope_typescript() -> str:
    from analyst.case_study.analytics import Scope
    from analyst.case_study.contracts import FinancialMetrics, Metrics

    defaults = Scope()
    members = fields(Scope)
    if any(not isinstance(getattr(defaults, item.name), str) for item in members):
        raise TypeError("The generated scope contract supports string filters only")
    declarations = [f"  {item.name}: string;" for item in members]
    values = [f"  {item.name}: {getattr(defaults, item.name)!r}," for item in members]
    return "\n".join(
        [
            "// Generated by scripts/generate_contracts.py. Edit the Python contracts instead.",
            "export type BackendScope = {",
            *declarations,
            "};",
            "",
            "export const initialBackendScope: BackendScope = {",
            *values,
            "};",
            "",
            *metric_typescript("BackendFinancialMetrics", FinancialMetrics.model_json_schema()),
            *metric_typescript("BackendMetrics", Metrics.model_json_schema()),
        ]
    )


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check", action="store_true", help="Fail if the generated contract is stale"
    )
    args = parser.parse_args()
    destination = ROOT / "frontend/src/generated-scope.ts"
    expected = scope_typescript()
    if args.check:
        if not destination.is_file() or destination.read_text(encoding="utf-8") != expected:
            print("Scope contract is stale. Run python scripts/generate_contracts.py")
            return 1
        print("Generated contracts match the Python engine")
        return 0
    destination.write_text(expected, encoding="utf-8", newline="\n")
    print(destination.relative_to(ROOT).as_posix())
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
